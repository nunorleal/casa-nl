import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const manifestPath = new URL('version.json', root);
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const match = /^(\d+)\.(\d{2})$/.exec(manifest.version);
if (!match) throw new Error('A versão deve ter o formato 1.00.');
let revision = Number(match[1]) * 100 + Number(match[2]);
if (!process.argv.includes('--sync')) revision += 1;
const version = `${Math.floor(revision / 100)}.${String(revision % 100).padStart(2, '0')}`;
const htmlPath = new URL('dist/index.html', root);
let html = readFileSync(htmlPath, 'utf8');
if (!/<span data-app-version>[^<]*<\/span>/.test(html)) throw new Error('Não foi encontrado o indicador de versão no topo.');
html = html.replace(/(<span data-app-version>)[^<]*(<\/span>)/, `$1Versão ${version}$2`);
html = html.replace(/(<meta name="application-version" content=")[^"]*(">)/, `$1${version}$2`);
html = html.replace(/((?:src|href)="[^":?#]+\.(?:js|css))(?:\?v=[^"]*)?"/g, `$1?v=${version}"`);
writeFileSync(htmlPath, html);
writeFileSync(manifestPath, JSON.stringify({ ...manifest, version }, null, 2) + '\n');
console.log(`Versão ${version}${process.argv.includes('--sync') ? ' sincronizada' : ' criada'}.`);
